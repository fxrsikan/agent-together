import fs from "node:fs";
import path from "node:path";
import type { CanvasNode } from "@loom/schema";

/** Claude Code skill names: lowercase letters, digits and hyphens, at most 64 characters. */
export const skillName = (nodeId: string) => `loom-${nodeId}`.toLowerCase().replace(/[^a-z0-9-]+/g, "-").slice(0, 64);

const yamlString = (s: string) => JSON.stringify(s); // a JSON string is a valid YAML double-quoted scalar

/**
 * Writes a node as a Claude Code skill at <root>/.claude/skills/<name>/SKILL.md.
 * `guide` is the node guide Markdown (core's buildNodeGuide). Returns the file path.
 */
export function exportSkill(root: string, node: CanvasNode, guide: string): string {
  const name = skillName(node.id);
  const scope = node.files.join(", ") || "its files";
  const description = `Work on "${node.title}"${node.intent.goal ? `: ${node.intent.goal}` : ""}. Use when changing ${scope}.`.slice(0, 1024);
  const file = path.join(root, ".claude", "skills", name, "SKILL.md");
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(
    file,
    `---\nname: ${name}\ndescription: ${yamlString(description)}\n---\n\n` +
      `<!-- Generated by Loom from canvas node "${node.id}". Edit the node in Loom and export again. -->\n\n${guide}`,
  );
  return file;
}
