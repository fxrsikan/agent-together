import { z } from "zod";

/**
 * A capability unit: written once in .loom/capabilities/<id>.md, compiled to
 * each agent's own format. See design doc "能力工坊".
 *   skill    — a way of doing something (SKILL.md, Cursor rule)
 *   agent    — a role: persona + tool access + model (Claude Code subagent)
 *   observer — a declarative rule Loom's observer enforces on every agent
 */
export const CapabilityKind = z.enum(["skill", "agent", "observer"]);

/** Same rule as Claude Code / Agent Skills names: lowercase letters, digits and hyphens, at most 64. */
export const CapabilityId = z.string().regex(/^[a-z0-9][a-z0-9-]{0,63}$/, "id must be lowercase letters, digits and hyphens, at most 64");

export const Capability = z.object({
  id: CapabilityId,
  kind: CapabilityKind,
  /** When to use it; agents see this before deciding to load the body. */
  description: z.string().min(1).max(1024),
  version: z.string().default("1"),
  /** The canvas node it was produced from, if any. */
  nodeId: z.string().nullable().default(null),
  /** Files it applies to (globs, project-relative). Empty = everywhere. */
  scope: z.array(z.string()).default([]),
  /** agent: tools the role may use (Claude Code tool names). */
  tools: z.array(z.string()).optional(),
  /** agent: model alias, e.g. "haiku" or "sonnet". */
  model: z.string().optional(),
  /** observer: regex that must not appear in text an agent writes within scope. */
  forbid: z.string().optional(),
  /** observer: intervention level when it matches. */
  level: z.enum(["log", "warn", "ask", "block"]).optional(),
  /** skill / agent: the instructions. observer: the message shown to the agent. */
  body: z.string().min(1),
});
export type Capability = z.infer<typeof Capability>;

/** The line every compiled file carries, so nobody edits the copy instead of the source. */
export const generatedNote = (c: Capability) =>
  `<!-- Generated by Loom from .loom/capabilities/${c.id}.md (v${c.version}). Edit it there and recompile. -->`;

/** One generated file. */
export interface CompiledFile {
  /** Project-relative posix path. */
  path: string;
  content: string;
}

/** Turns a capability into one platform's files; [] when that platform has no equivalent. */
export interface CapabilityCompiler {
  target: string;
  compile(capability: Capability): CompiledFile[];
}
