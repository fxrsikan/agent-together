import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { claudeCodeCompiler, installHooks, toHookOutput, toAgentEvent } from "@agent-together/adapter-claude-code";
import { cleanEnv } from "@agent-together/core";
import { Capability } from "@agent-together/schema";

describe("claudeCodeCompiler", () => {
  const base = { description: 'Work on "登录表单". Use when changing src/auth/**.', body: "## 节点：登录表单" };

  it("compiles a skill to .claude/skills/<id>/SKILL.md with a quoted description", () => {
    const [file] = claudeCodeCompiler.compile(Capability.parse({ ...base, id: "agent-together-login-form", kind: "skill" }));
    expect(file.path).toBe(".claude/skills/agent-together-login-form/SKILL.md");
    expect(file.content).toMatch(/^---\nname: agent-together-login-form\ndescription: "Work on \\"登录表单\\". Use when changing src\/auth\/\*\*."\n---/);
    expect(file.content).toContain("Generated by Agent Together");
    expect(file.content).toContain("## 节点：登录表单");
  });

  it("compiles an agent role to a subagent with tools and model", () => {
    const [file] = claudeCodeCompiler.compile(
      Capability.parse({ ...base, id: "reviewer", kind: "agent", tools: ["Read", "Grep"], model: "haiku" }),
    );
    expect(file.path).toBe(".claude/agents/reviewer.md");
    expect(file.content).toContain("tools: Read, Grep\nmodel: haiku\n---");
  });

  it("produces nothing for observers, which Agent Together enforces itself", () => {
    expect(claudeCodeCompiler.compile(Capability.parse({ ...base, id: "no-log", kind: "observer", forbid: "x" }))).toEqual([]);
  });
});

describe("cleanEnv", () => {
  it("drops host-session CLAUDE* variables and keeps the user's ANTHROPIC_* settings", () => {
    const env = cleanEnv({ CLAUDECODE: "1", CLAUDE_CODE_SESSION_ID: "x", ANTHROPIC_API_KEY: "k", PATH: "p" });
    expect(env).toEqual({ ANTHROPIC_API_KEY: "k", PATH: "p" });
  });
});

const base = { session_id: "s1", cwd: "/proj" };

describe("toAgentEvent", () => {
  it("maps an Edit before it runs to a write with before/after", () => {
    const event = toAgentEvent({
      ...base,
      hook_event_name: "PreToolUse",
      tool_name: "Edit",
      tool_input: { file_path: "/proj/a.ts", old_string: "a", new_string: "b" },
    });
    expect(event).toMatchObject({
      kind: "tool.before",
      action: { type: "write", path: "/proj/a.ts", before: "a", after: "b" },
    });
  });

  it("reads the current file for a Write so rules can compare", () => {
    const event = toAgentEvent(
      { ...base, hook_event_name: "PreToolUse", tool_name: "Write", tool_input: { file_path: "/proj/a.ts", content: "new" } },
      () => "old",
    );
    expect(event).toMatchObject({ action: { before: "old", after: "new" } });
  });

  it("maps a failed Bash call to a failed shell event", () => {
    const event = toAgentEvent({
      ...base,
      hook_event_name: "PostToolUseFailure",
      tool_name: "Bash",
      tool_input: { command: "npm test" },
      error: "exit 1",
    });
    expect(event).toMatchObject({ kind: "tool.after", ok: false, action: { type: "shell", command: "npm test" } });
  });

  it("ignores events Agent Together does not use", () => {
    expect(toAgentEvent({ ...base, hook_event_name: "Notification" })).toBeNull();
  });

  // Grok Build runs Claude settings hooks with its own tool names (shapes from a real Grok 1.0.70 run).
  it("reads Grok Build's tool names and marks the platform", () => {
    const grok = { ...base, hookEventName: "pre_tool_use" };
    const edit = toAgentEvent({
      ...grok,
      hook_event_name: "PreToolUse",
      tool_name: "search_replace",
      tool_input: { file_path: "/p/src/a.ts", old_string: "a", new_string: "b" },
    });
    expect(edit).toMatchObject({ platform: "grok-build", action: { type: "write", path: "/p/src/a.ts", before: "a", after: "b" } });
    const read = toAgentEvent({ ...grok, hook_event_name: "PreToolUse", tool_name: "read_file", tool_input: { target_file: "/p/x.ts" } });
    expect(read).toMatchObject({ action: { type: "read", path: "/p/x.ts" } });
  });

  it("treats a Grok Build shell result with a non-zero exit code as a failure", () => {
    const shell = { ...base, hookEventName: "post_tool_use", hook_event_name: "PostToolUse", tool_name: "run_terminal_command", tool_input: { command: "npm test" } };
    expect(toAgentEvent({ ...shell, toolResult: { type: "Bash", exit_code: 1 } })).toMatchObject({ ok: false, error: "exit 1", action: { type: "shell" } });
    expect(toAgentEvent({ ...shell, toolResult: { type: "Bash", exit_code: 0 } })).toMatchObject({ ok: true });
  });
});

describe("toHookOutput", () => {
  const finding = { rule: "scope-fence", message: "outside node" };

  it("denies a blocked tool call", () => {
    const out = JSON.parse(toHookOutput("PreToolUse", { level: "block", findings: [{ ...finding, level: "block" }] })!);
    expect(out.hookSpecificOutput.permissionDecision).toBe("deny");
  });

  it("asks the user on ask", () => {
    const out = JSON.parse(toHookOutput("PreToolUse", { level: "ask", findings: [{ ...finding, level: "ask" }] })!);
    expect(out.hookSpecificOutput.permissionDecision).toBe("ask");
  });

  it("adds context after a tool ran", () => {
    const out = JSON.parse(toHookOutput("PostToolUse", { level: "warn", findings: [{ ...finding, level: "warn" }] })!);
    expect(out.hookSpecificOutput.additionalContext).toContain("outside node");
  });

  it("prints nothing when only logging", () => {
    expect(toHookOutput("PreToolUse", { level: "log", findings: [{ ...finding, level: "log" }] })).toBeNull();
  });
});

describe("installHooks", () => {
  it("adds Agent Together hooks once and keeps other settings", () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "agent-together-"));
    const file = path.join(dir, ".claude", "settings.local.json");
    fs.mkdirSync(path.dirname(file));
    fs.writeFileSync(file, JSON.stringify({ model: "x", hooks: { Stop: [{ hooks: [{ type: "command", command: "say done" }] }] } }));
    installHooks(dir, "node /x/agent-together-hook.js");
    installHooks(dir, "node /x/agent-together-hook.js");
    const settings = JSON.parse(fs.readFileSync(file, "utf8"));
    expect(settings.model).toBe("x");
    expect(settings.hooks.PreToolUse).toHaveLength(1);
    expect(settings.hooks.Stop).toHaveLength(2);
  });
});
